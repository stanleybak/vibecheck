"""Tests for cex_check_v2 — vibecheck's VNNLIB-2.0 counterexample validator.

Two things are pinned here:

1. GOLDEN VERDICTS (approach C): a deterministic corpus of (onnx, spec, ce)
   triples with the accept/reject verdict FROZEN from the VNN-COMP 2026
   competition checker. The frozen values were generated by replaying each case
   through the (now-removed) vendored `vnncomp_cex_v2` checker (single-net via `validate_cex_v2`,
   multi-net via its `validate_vnnlib2_counterexample` network-field list) — see
   `scratch/gen_cex_golden.py`. cex_check_v2 must reproduce every verdict, so a
   `sat` vibecheck emits is accepted by the scorer and vice-versa. This is the
   bit-identical guarantee that lets us drop the vendored competition code.

2. BRANCH COVERAGE: the error dispositions (NO_CE / MALFORMED_CE / UNSUPPORTED)
   and the arithmetic/boolean evaluation paths.
"""
import os
import tempfile

import numpy as np
import onnx
import pytest
from onnx import TensorProto, helper, numpy_helper

from vibecheck.cex_check_v2 import (
    validate_cex_v2, ACCEPTED_RESULTS, CexResult, parse_text_assignment,
)


# --------------------------------------------------------------------------- #
# ONNX + spec + counterexample builders (deterministic).
# --------------------------------------------------------------------------- #
def _save_onnx(model, tmp, name):
    path = os.path.join(tmp, name)
    onnx.save(model, path)
    return path


def _gemm_model(W, b, in_dim, out_dim):
    Wt = numpy_helper.from_array(np.asarray(W, np.float32), name='W')
    bt = numpy_helper.from_array(np.asarray(b, np.float32), name='b')
    inp = helper.make_tensor_value_info('X', TensorProto.FLOAT, [1, in_dim])
    out = helper.make_tensor_value_info('Y', TensorProto.FLOAT, [1, out_dim])
    node = helper.make_node('Gemm', ['X', 'W', 'b'], ['Y'], transB=1)
    graph = helper.make_graph([node], 'm', [inp], [out], initializer=[Wt, bt])
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid('', 13)])
    model.ir_version = 7
    return model


def first_coord_net(tmp, name='first.onnx'):
    """Y[1,1] = X[0,0]  (W = [[1,0]])."""
    return _save_onnx(_gemm_model([[1.0, 0.0]], [0.0], 2, 1), tmp, name)


def scaled_id_net(tmp, scale, name):
    """Y[1,2] = scale * X[1,2]."""
    W = (scale * np.eye(2)).tolist()
    return _save_onnx(_gemm_model(W, [0.0, 0.0], 2, 2), tmp, name)


def _write(tmp, name, text):
    path = os.path.join(tmp, name)
    with open(path, 'w') as f:
        f.write(text)
    return path


def single_spec(tmp, out_assert, lo=(0.0, 0.0), hi=(1.0, 1.0), name='s.vnnlib'):
    text = ("(vnnlib-version <2.0>)\n"
            "(declare-network f (declare-input X real [1,2]) (declare-output Y real [1,1]))\n"
            f"(assert (>= X[0,0] {lo[0]}))\n(assert (<= X[0,0] {hi[0]}))\n"
            f"(assert (>= X[0,1] {lo[1]}))\n(assert (<= X[0,1] {hi[1]}))\n"
            f"(assert {out_assert})\n")
    return _write(tmp, name, text)


def single_ce(tmp, x0, x1, y, name='c.ce'):
    return _write(tmp, name, f"X real [1,2]\n{x0!r}\n{x1!r}\nY real [1,1]\n{y!r}\n")


def pair_spec(tmp, link, out_assert, name='p.vnnlib'):
    text = ("(vnnlib-version <2.0>)\n"
            "(declare-network f (declare-input X_f real [1,2]) (declare-output Y_f real [1,2]))\n"
            f"(declare-network g {link} (declare-input X_g real [1,2]) (declare-output Y_g real [1,2]))\n"
            "(assert (>= X_f[0,0] 0.0))(assert (<= X_f[0,0] 1.0))(assert (>= X_f[0,1] 0.0))(assert (<= X_f[0,1] 1.0))\n"
            "(assert (>= X_g[0,0] 0.0))(assert (<= X_g[0,0] 1.0))(assert (>= X_g[0,1] 0.0))(assert (<= X_g[0,1] 1.0))\n"
            f"(assert {out_assert})\n")
    return _write(tmp, name, text)


def pair_nets(tmp, link, scale):
    """Build (path_f, path_g) as vibecheck's resolve_pair_paths would: an
    `equal-to` g IS f, so it reuses f's ONE onnx path; an isomorphic g is a
    distinct net with its own path."""
    pf = scaled_id_net(tmp, 1.0, 'f.onnx')
    pg = pf if link == '(equal-to f)' else scaled_id_net(tmp, scale, 'g.onnx')
    return pf, pg


def pair_ce(tmp, xf, yf, xg, yg, name='p.ce'):
    return _write(tmp, name,
                  f"X_f real [1,2]\n{xf[0]!r}\n{xf[1]!r}\nY_f real [1,2]\n{yf[0]!r}\n{yf[1]!r}\n"
                  f"X_g real [1,2]\n{xg[0]!r}\n{xg[1]!r}\nY_g real [1,2]\n{yg[0]!r}\n{yg[1]!r}\n")


