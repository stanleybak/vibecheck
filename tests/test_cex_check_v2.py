def _double_id_net(tmp, name='dbl.onnx'):
    """Identity [1,2] -> [1,2] with DOUBLE (float64) element type."""
    inp = helper.make_tensor_value_info('X', TensorProto.DOUBLE, [1, 2])
    out = helper.make_tensor_value_info('Y', TensorProto.DOUBLE, [1, 2])
    node = helper.make_node('Identity', ['X'], ['Y'])
    graph = helper.make_graph([node], 'm', [inp], [out])
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid('', 13)])
    model.ir_version = 7
    return _save_onnx(model, tmp, name)


