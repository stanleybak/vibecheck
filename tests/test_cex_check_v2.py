# 2. Golden verdicts — network pairs (multi-onnx).
# --------------------------------------------------------------------------- #
# (link, out_assert, xf, xg, g_scale, expected)  — f = identity, g = g_scale*X.
_PAIR_GOLDEN = [
    ('iso_true',   '(isomorphic-to f)', '(> Y_f[0,0] Y_g[0,0])', (0.9, 0.1), (0.1, 0.1), 2.0, CexResult.CORRECT),
    ('iso_false',  '(isomorphic-to f)', '(> Y_f[0,0] Y_g[0,0])', (0.1, 0.1), (0.9, 0.1), 2.0, CexResult.SPEC_NOT_VIOLATED),
    ('iso_in_tol', '(isomorphic-to f)', '(> Y_f[0,0] Y_g[0,0])', (0.9, 0.1), (-5e-5, 0.1), 2.0, CexResult.CORRECT_UP_TO_TOLERANCE),
    ('iso_far',    '(isomorphic-to f)', '(> Y_f[0,0] Y_g[0,0])', (0.9, 0.1), (1.5, 0.1), 2.0, CexResult.SPEC_NOT_VIOLATED),
    ('iso_or',     '(isomorphic-to f)', '(or (> Y_f[0,0] Y_g[0,0]) (> Y_f[0,1] 5.0))', (0.9, 0.1), (0.1, 0.1), 2.0, CexResult.CORRECT),
    ('mono_true',  '(equal-to f)',      '(> Y_f[0,0] Y_g[0,0])', (0.9, 0.1), (0.1, 0.1), 1.0, CexResult.CORRECT),
    ('mono_bound', '(equal-to f)',      '(> Y_f[0,0] Y_g[0,0])', (0.5, 0.1), (0.5, 0.1), 1.0, CexResult.SPEC_NOT_VIOLATED),
    # arithmetic in the output atom (exercises Plus/Minus/Multiply):
    ('arith_plus', '(equal-to f)',      '(> Y_f[0,0] (+ Y_g[0,0] 0.1))', (0.9, 0.1), (0.1, 0.1), 1.0, CexResult.CORRECT),
    ('arith_minus','(equal-to f)',      '(> (- Y_f[0,0] Y_g[0,0]) 0.05)', (0.9, 0.1), (0.1, 0.1), 1.0, CexResult.CORRECT),
    ('arith_mul',  '(equal-to f)',      '(> (* Y_f[0,0] 2.0) 1.0)', (0.9, 0.1), (0.1, 0.1), 1.0, CexResult.CORRECT),
]


@pytest.mark.parametrize('name,link,out,xf,xg,scale,expected', _PAIR_GOLDEN,
                         ids=[c[0] for c in _PAIR_GOLDEN])
def test_pair_golden(tmp_path, name, link, out, xf, xg, scale, expected):
    tmp = str(tmp_path)
    pf, pg = pair_nets(tmp, link, scale)
    spec_p = pair_spec(tmp, link, out)
    yf = (xf[0], xf[1])
    yg = (xg[0] * scale, xg[1] * scale)
    ce_p = pair_ce(tmp, xf, yf, xg, yg)
    result, _ = validate_cex_v2([('f', pf), ('g', pg)], spec_p, ce_p)
    assert result == expected


