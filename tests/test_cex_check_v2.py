# 1. Golden verdicts — single network.
# --------------------------------------------------------------------------- #
# (out_assert, x0, x1, expected result)  — Y = X[0,0].
_SINGLE_GOLDEN = [
    ('gt_clear',      '(> Y[0,0] 0.5)',  0.9,   0.3, CexResult.CORRECT),
    ('gt_boundary',   '(> Y[0,0] 0.5)',  0.5,   0.3, CexResult.SPEC_NOT_VIOLATED),
    ('gt_below',      '(> Y[0,0] 0.5)',  0.4,   0.3, CexResult.SPEC_NOT_VIOLATED),
    ('lt_clear',      '(< Y[0,0] 0.5)',  0.1,   0.3, CexResult.CORRECT),
    ('lt_boundary',   '(< Y[0,0] 0.5)',  0.5,   0.3, CexResult.SPEC_NOT_VIOLATED),
    ('ge_boundary',   '(>= Y[0,0] 0.5)', 0.5,   0.3, CexResult.CORRECT),
    ('le_boundary',   '(<= Y[0,0] 0.5)', 0.5,   0.3, CexResult.CORRECT),
    ('in_tol_low',    '(< Y[0,0] 0.5)', -5e-5,  0.3, CexResult.CORRECT_UP_TO_TOLERANCE),
    ('in_tol_high',   '(> Y[0,0] 0.5)',  1.00005, 0.3, CexResult.CORRECT_UP_TO_TOLERANCE),
    ('far_outside',   '(> Y[0,0] 0.5)',  1.5,   0.3, CexResult.SPEC_NOT_VIOLATED),
    ('below_tol',     '(< Y[0,0] 0.5)', -1e-3,  0.3, CexResult.SPEC_NOT_VIOLATED),
]


@pytest.mark.parametrize('name,out,x0,x1,expected', _SINGLE_GOLDEN,
                         ids=[c[0] for c in _SINGLE_GOLDEN])
def test_single_golden(tmp_path, name, out, x0, x1, expected):
    tmp = str(tmp_path)
    onnx_p = first_coord_net(tmp)
    spec_p = single_spec(tmp, out)
    ce_p = single_ce(tmp, x0, x1, float(x0))
    result, _ = validate_cex_v2(onnx_p, spec_p, ce_p)
    assert result == expected
    assert (result in ACCEPTED_RESULTS) == (
        expected in (CexResult.CORRECT, CexResult.CORRECT_UP_TO_TOLERANCE))


