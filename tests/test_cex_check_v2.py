def _gzip(path):
    import gzip
    with open(path, 'rb') as f:
        data = f.read()
    gz = path + '.gz'
    with gzip.open(gz, 'wb') as f:
        f.write(data)
    return gz


def test_gz_spec_and_onnx(tmp_path):
    """.gz-compressed spec and onnx are read transparently."""
    tmp = str(tmp_path)
    onnx_gz = _gzip(first_coord_net(tmp))
    spec_gz = _gzip(single_spec(tmp, '(> Y[0,0] 0.5)'))
    ce_p = single_ce(tmp, 0.9, 0.3, 0.9)
    result, _ = validate_cex_v2(onnx_gz, spec_gz, ce_p)
    assert result == CexResult.CORRECT


def test_negate_and_and_boolean_atoms(tmp_path):
    """Output atoms exercising Negate and a boolean And (not the box fast path)."""
    tmp = str(tmp_path)
    pf = scaled_id_net(tmp, 1.0, 'f.onnx')
