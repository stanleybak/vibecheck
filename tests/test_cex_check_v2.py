def test_single_path_with_pair_spec(tmp_path):
    """A single onnx path can't satisfy a 2-implemented-network spec."""
    tmp = str(tmp_path)
    pf = scaled_id_net(tmp, 1.0, 'f.onnx')
    spec_p = pair_spec(tmp, '(isomorphic-to f)', '(> Y_f[0,0] Y_g[0,0])')
    ce_p = pair_ce(tmp, (0.9, 0.1), (0.9, 0.1), (0.1, 0.1), (0.2, 0.2))
    result, msg = validate_cex_v2(pf, spec_p, ce_p)
    assert result == CexResult.UNSUPPORTED and 'exactly one implemented network' in msg


